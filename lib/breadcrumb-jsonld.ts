// Shared BreadcrumbList builder. Items should mirror what's visibly
// rendered as the page's breadcrumb trail — Google's structured data
// guidelines require the markup to match visible content.
export function buildBreadcrumbJsonLd(items: { name: string; url: string }[]) {
  return {
    "@context": "https://schema.org",
    "@type": "BreadcrumbList",
    itemListElement: items.map((item, i) => ({
      "@type": "ListItem",
      position: i + 1,
      name: item.name,
      item: item.url,
    })),
  }
}
